import {test} from 'node:test';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {readFile} from 'node:fs/promises';
import {build} from 'esbuild';
import {JSDOM} from 'jsdom';

const shell=await readFile(new URL('../web/index.html',import.meta.url),'utf8');
const app=(await build({entryPoints:[fileURLToPath(new URL('../web/app.js',import.meta.url))],bundle:true,write:false,format:'iife'})).outputFiles[0].text;
const anchor={type:'text',exact:'Text',prefix:'',suffix:'',position:{start:0,end:4}};
const thread={id:'thread-1',anchor,status:'open',threadRevision:1,messages:[{id:'message-1',author:{id:'me',displayName:'Me'},body:'Existing',createdAt:'2026-11-01T00:00:00Z',canDelete:true}]};
const comments=(threads=[],revision=0)=>({threads,revision,canWrite:true,versionToken:String(revision)});
const data=(overrides={})=>({documentId:'doc',versionId:'v1',sourceHash:'a'.repeat(64),title:'Document',html:'<p>Text</p>',pagePath:'index.html',pages:['index.html','second.html'],versions:[{versionId:'v1',createdAt:'2026-11-01T00:00:00Z'}],canReadComments:true,canWriteComments:true,canAppend:true,comments:comments(),...overrides});
const deferred=()=>{let resolve,reject;const promise=new Promise((a,b)=>{resolve=a;reject=b;});return {promise,resolve,reject};};
const flush=()=>new Promise(resolve=>setImmediate(resolve));
async function ui(t,{documentValue=data(),library=false}={}) {
  const dom=new JSDOM(shell,{url:'https://test.example/',runScripts:'outside-only',pretendToBeVisual:true});
  t.after(()=>dom.window.close());
  const w=dom.window,requests=[],timers=new Map();
  let timer=0;
  w.structuredClone=structuredClone;w.TextDecoder=TextDecoder;
  // Control background prefetch/poll independently from response completion.
  w.setTimeout=(fn,delay)=>{timers.set(++timer,{fn,delay});return timer;};
  w.clearTimeout=id=>timers.delete(id);
  w.SHSS_BOOT=library?{}:{documentId:'doc',versionId:'v1'};
  w.SHSS_BRIDGE='/* __SHSS_CONTEXT__ */';
  w.SHSS_API=(action,input)=>{const d=deferred();requests.push({action,input,...d});return d.promise;};
  w.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
  w.HTMLDialogElement.prototype.close=function(value=''){this.open=false;this.returnValue=value;this.dispatchEvent(new w.Event('close'));};
  w.eval(app);await flush();
  const respond=async(request,value)=>{request.resolve({ok:true,value});await flush();};
  if(library)await respond(requests[0],{documents:[{documentId:'doc',latestVersionId:'v1',title:'Document',updatedAt:'2026-11-01'}],canImport:false});
  else await respond(requests[0],documentValue);
  const el=id=>w.document.getElementById(id);
  const last=action=>requests.filter(r=>r.action===action).at(-1);
  const submit=()=>el('compose').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
  const sendPreview=p=>{
    const frame=el('preview').querySelector('iframe');
    // Match the per-frame session generated by the real application.
    const source=frame.srcdoc.match(/\/\* (\{.*?\}) \*\//)[1],context=JSON.parse(source);
    w.dispatchEvent(new w.MessageEvent('message',{source:frame.contentWindow,origin:'null',data:{...context,...p}}));
  };
  const choose=(selectedAnchor=anchor)=>{
    sendPreview({type:'ready',highlights:true});sendPreview({type:'selection',anchor:selectedAnchor});
  };
  const background=async()=>{
    const entry=[...timers].find(([,timer])=>timer.delay===250);
    assert.ok(entry,'expected a queued prefetch');
    timers.delete(entry[0]);entry[1].fn();await flush();
  };
  return {w,el,requests,last,respond,submit,choose,sendPreview,background};
}

test('a cached page submits before validation completes and a late read keeps the confirmed post',async t=>{
  const u=await ui(t,{library:true});
  await u.background();await u.respond(u.last('getDocument'),data({comments:{...comments(),epoch:'restored-epoch'}}));
  u.el('documents').querySelector('button').click();await flush();
  const validation=u.last('getDocument');
  u.choose();u.el('body').value='No validation wait';u.submit();await flush();
  const save=u.last('submitOperation');assert.ok(save);
  assert.equal(save.input.epoch,'restored-epoch');
  assert.match(u.el('threads').textContent,/No validation wait/);
  const saved={...thread,id:'new-thread',messages:[{...thread.messages[0],body:'No validation wait',operationId:save.input.operationId}]};
  await u.respond(save,{status:'applied',operationId:save.input.operationId,threadId:'new-thread',comments:{...comments([saved],1),epoch:'restored-epoch'}});
  await u.respond(validation,data({comments:{...comments(),epoch:'restored-epoch'}}));
  assert.match(u.el('threads').textContent,/No validation wait/);
  assert.doesNotMatch(u.el('threads').textContent,/保存中/);
});

test('a provisional post denied by the server restores its draft and disables resubmission',async t=>{
  const u=await ui(t,{library:true});
  await u.background();await u.respond(u.last('getDocument'),data());
  u.el('documents').querySelector('button').click();await flush();
  u.choose();u.el('body').value='Keep this draft';u.submit();await flush();
  u.last('submitOperation').resolve({ok:false,error:{code:'FORBIDDEN',message:'Permission changed'}});await flush();
  assert.equal(u.el('body').value,'Keep this draft');
  assert.equal(u.el('submit').disabled,true);
  assert.doesNotMatch(u.el('threads').textContent,/Keep this draft/);
  u.el('save-details').click();
  assert.match(u.el('save-list').textContent,/Keep this draft/);
});


test('returning to a page shows its confirmed save before the validation response',async t=>{
  const u=await ui(t);u.choose();u.el('body').value='Saved on first page';u.submit();await flush();
  const save=u.last('submitOperation');
  u.el('pages').value='second.html';u.el('pages').dispatchEvent(new u.w.Event('change'));await flush();
  await u.respond(u.last('getDocument'),data({pagePath:'second.html'}));
  const saved={...thread,messages:[{...thread.messages[0],body:'Saved on first page',operationId:save.input.operationId}]};
  await u.respond(save,{status:'applied',operationId:save.input.operationId,threadId:thread.id,comments:comments([saved],1)});
  u.el('pages').value='index.html';u.el('pages').dispatchEvent(new u.w.Event('change'));await flush();
  assert.match(u.el('load-status').textContent,/確認中/);
  assert.match(u.el('threads').textContent,/Saved on first page/);
});


test('older cached comments stay visible while new posting waits for a fresh epoch',async t=>{
  const u=await ui(t,{library:true});
  await u.background();await u.respond(u.last('getDocument'),data({comments:comments([thread]),commentsStale:true}));
  u.el('documents').querySelector('button').click();await flush();
  assert.match(u.el('threads').textContent,/Existing/);
  assert.equal(u.el('submit').disabled,true);
  u.choose();u.el('body').value='Draft while updating';
  assert.equal(u.el('body').disabled,false);
  await u.respond(u.last('getDocument'),data({comments:comments([thread])}));
  assert.equal(u.el('submit').disabled,false);
  assert.equal(u.el('body').value,'Draft while updating');
});
